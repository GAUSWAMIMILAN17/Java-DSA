package TCS_String;

public class ASCIIVALUES {
    static void main(String[] args) {
        String s = "a";
        if(s.charAt(0) >= 'A' && s.charAt(0) <= 'Z') {
            System.out.println((int) s.charAt(0));
        } else {
            System.out.println((int)s.charAt(0));
        }
    }
}
